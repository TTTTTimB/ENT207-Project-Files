let currentLang = "zh";
try {
  const saved = window.localStorage.getItem(LANG_KEY);
  if (saved === "en") currentLang = "en";
} catch {
  // 忽略：隐私模式或 file:// 下 localStorage 不可用
}
if (typeof document !== "undefined") {
  document.documentElement.lang = currentLang === "en" ? "en" : "zh-CN";
}

export function getLanguage() {
  return currentLang;
}

export function setLanguage(next) {
  currentLang = next === "en" ? "en" : "zh";
  try {
    window.localStorage.setItem(LANG_KEY, currentLang);
  } catch {
    // 忽略：无法持久化时仅影响本次会话
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = currentLang === "en" ? "en" : "zh-CN";
  }
}

// 需在中文源文案中保留的占位符，例如 t("共 {n} 家店铺", { n: 21 })
export function t(text, vars) {
  if (text === undefined || text === null) return "";
  const source = String(text);
  const translated = currentLang === "en" ? (EN[source] ?? source) : source;
  if (!vars) return translated;
  return translated.replace(/\{(\w+)\}/g, (match, key) => (vars[key] !== undefined ? String(vars[key]) : match));
}

export function hasTranslation(text) {
  return Object.prototype.hasOwnProperty.call(EN, String(text));
}

